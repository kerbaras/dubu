// Starter workspaces. Each one is a set of files written to /workspace.
export interface Example {
  id: string;
  title: string;
  hint: string;
  files: Record<string, string>;
}

const basics = `# Everything here runs in your browser: the real OpenTofu CLI compiled to
# WebAssembly. Try the console below, e.g.  upper(local.greeting)

variable "name" {
  type    = string
  default = "tofu"
}

variable "regions" {
  type    = list(string)
  default = ["eu-west-1", "us-east-1", "ap-south-1"]
}

locals {
  greeting = "hello, \${var.name}!"
  zones    = { for r in var.regions : r => [for z in ["a", "b"] : "\${r}\${z}"] }
  tags = {
    project = var.name
    managed = "opentofu"
  }
}

resource "random_pet" "server" {
  length = 2
  prefix = var.name
}

resource "terraform_data" "build" {
  input = merge(local.tags, { pet = random_pet.server.id })
}

output "greeting" {
  value = local.greeting
}

output "server" {
  value = random_pet.server.id
}
`;

const functions = `# A tour of expressions. Evaluate any of these in the console:
#   local.slugs
#   cidrsubnets(local.cidr, 4, 4, 8)
#   jsondecode(local.doc).services[*].port
#   templatestring(local.tpl, { name = "tofu" })

locals {
  names = ["Alpha Service", "beta_service", "Gamma-Service"]
  slugs = [for n in local.names : lower(replace(n, "/[^a-zA-Z0-9]+/", "-"))]
  cidr  = "10.0.0.0/16"
  doc   = jsonencode({ services = [{ name = "api", port = 8080 }, { name = "web", port = 443 }] })
  tpl   = "Hello, \${name}!"
  sizes = { small = 1, medium = 2, large = 4 }
  total = sum(values(local.sizes))
}
`;

const resources = `# Bundled providers: random, null, local, time and http.
# Run: tofu init, then tofu plan, then tofu apply. State is kept in your browser.

terraform {
  required_providers {
    random = { source = "hashicorp/random" }
    time   = { source = "hashicorp/time" }
    local  = { source = "hashicorp/local" }
  }
}

resource "random_password" "db" {
  length  = 20
  special = false
}

resource "random_shuffle" "az" {
  input        = ["a", "b", "c", "d"]
  result_count = 2
}

resource "time_static" "created" {}

resource "local_file" "readme" {
  filename = "\${path.module}/README.generated.md"
  content  = <<-EOT
    # Generated by OpenTofu
    Created at \${time_static.created.rfc3339}
    Zones: \${join(", ", random_shuffle.az.result)}
  EOT
}

output "zones" {
  value = random_shuffle.az.result
}

output "password" {
  value     = random_password.db.result
  sensitive = true
}
`;

const http = `# The http provider uses the browser's fetch, so the API must allow CORS.

data "http" "repo" {
  url = "https://api.github.com/repos/opentofu/opentofu"
  request_headers = {
    Accept = "application/vnd.github+json"
  }
}

locals {
  repo = jsondecode(data.http.repo.response_body)
}

output "stars" {
  value = local.repo.stargazers_count
}

output "license" {
  value = local.repo.license.name
}
`;

export const examples: Example[] = [
  { id: "basics", title: "Variables & locals", hint: "tofu console", files: { "main.tf": basics } },
  { id: "functions", title: "Expressions tour", hint: "tofu console", files: { "main.tf": functions } },
  {
    id: "resources",
    title: "Resources & state",
    hint: "tofu init, then tofu apply",
    files: { "main.tf": resources, "variables.tf": `variable "env" {\n  type    = string\n  default = "dev"\n}\n` },
  },
  { id: "http", title: "Fetch data over HTTP", hint: "tofu plan", files: { "main.tf": http } },
];
